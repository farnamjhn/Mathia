//! Light and dark Dock icons on macOS.
//!
//! macOS renders a bundled app's icon itself and applies the user's
//! Default/Dark/Clear/Tinted icon appearance to it. A development launch is a
//! raw executable, though, and Tauri assigns it a static raster icon, so the
//! running Dock tile would otherwise stay light no matter which icon style the
//! user picked.
//!
//! The running app therefore sets its Dock tile from the
//! `AppleIconAppearanceTheme` preference, falling back to the system Light/Dark
//! appearance only when the style is `Automatic`. A watcher re-reads the
//! preference, leaving the tile unchanged for Clear and Tinted. Changing
//! between Default and Dark in System Settings updates the tile
//! without a relaunch. Both PNGs are generated by `scripts/make-icons.sh`.
//! Elsewhere this is a no-op.

use tauri::Theme;

/// Resolves which Dock icon variant to show given the system Light/Dark
/// appearance and macOS 26+'s optional `AppleIconAppearanceTheme` setting.
#[cfg_attr(not(target_os = "macos"), allow(dead_code))]
fn resolve_theme(system_theme: Theme, icon_appearance: Option<&str>) -> Option<Theme> {
    match icon_appearance {
        Some("RegularDark") => Some(Theme::Dark),
        Some("RegularAutomatic") => Some(system_theme),
        Some(value) if value.starts_with("Clear") || value.starts_with("Tinted") => None,
        _ => Some(Theme::Light),
    }
}

#[cfg(target_os = "macos")]
mod macos {
    use std::sync::atomic::{AtomicU8, Ordering};
    use std::time::Duration;

    use objc2::{AllocAnyThread, MainThreadMarker};
    use objc2_app_kit::{
        NSAppearanceNameAqua, NSAppearanceNameDarkAqua, NSApplication, NSImage, NSImageView,
    };
    use objc2_foundation::{NSArray, NSData, NSUserDefaults, ns_string};
    use tauri::Theme;

    const UNSET: u8 = 0;
    const LIGHT: u8 = 1;
    const DARK: u8 = 2;

    static APPLIED: AtomicU8 = AtomicU8::new(UNSET);

    pub(super) static LIGHT_BYTES: &[u8] = include_bytes!("../icons/dock-light.png");
    pub(super) static DARK_BYTES: &[u8] = include_bytes!("../icons/dock-dark.png");

    fn encode(theme: Theme) -> u8 {
        match theme {
            Theme::Dark => DARK,
            _ => LIGHT,
        }
    }

    fn effective_system_theme(mtm: MainThreadMarker) -> Theme {
        let app = NSApplication::sharedApplication(mtm);
        let appearance = app.effectiveAppearance();
        let names =
            unsafe { NSArray::from_slice(&[NSAppearanceNameAqua, NSAppearanceNameDarkAqua]) };
        let is_dark = appearance
            .bestMatchFromAppearancesWithNames(&names)
            .is_some_and(|name| unsafe { &*name == NSAppearanceNameDarkAqua });
        if is_dark { Theme::Dark } else { Theme::Light }
    }

    /// Reads the user's Icon & widget style. `synchronize` is required: without
    /// it the in-process defaults cache never sees a change made in System
    /// Settings by another process.
    fn icon_appearance_default() -> Option<String> {
        let defaults = NSUserDefaults::standardUserDefaults();
        defaults.synchronize();
        defaults
            .stringForKey(ns_string!("AppleIconAppearanceTheme"))
            .map(|s| s.to_string())
    }

    pub(super) fn decode_icon(bytes: &[u8]) -> Option<objc2::rc::Retained<NSImage>> {
        let data = NSData::with_bytes(bytes);
        NSImage::initWithData(NSImage::alloc(), &data)
    }

    pub(super) fn apply(hint: Option<Theme>, force: bool) {
        // AppKit requires Dock icon updates on the main thread; anything else skips.
        let Some(mtm) = MainThreadMarker::new() else {
            return;
        };

        let app = NSApplication::sharedApplication(mtm);
        let system_theme = hint.unwrap_or_else(|| effective_system_theme(mtm));
        let Some(resolved) =
            super::resolve_theme(system_theme, icon_appearance_default().as_deref())
        else {
            return;
        };
        let code = encode(resolved);

        let dock_tile = app.dockTile();
        let has_content_view = dock_tile.contentView(mtm).is_some();
        if !force && has_content_view && APPLIED.load(Ordering::Relaxed) == code {
            return;
        }

        let bytes = if resolved == Theme::Dark {
            DARK_BYTES
        } else {
            LIGHT_BYTES
        };
        let Some(image) = decode_icon(bytes) else {
            return;
        };

        #[allow(unused_unsafe)]
        unsafe {
            app.setApplicationIconImage(Some(&image));
        }
        let image_view = NSImageView::imageViewWithImage(&image, mtm);
        dock_tile.setContentView(Some(&image_view));
        dock_tile.display();
        APPLIED.store(code, Ordering::Relaxed);
    }

    /// Re-checks the icon style once a second so a change in System Settings
    /// reaches the running Dock tile.
    pub(super) fn spawn_watcher(app: tauri::AppHandle) {
        std::thread::spawn(move || {
            loop {
                std::thread::sleep(Duration::from_secs(1));
                if app.run_on_main_thread(|| apply(None, false)).is_err() {
                    break;
                }
            }
        });
    }
}

/// Applies the Dock icon unconditionally, reading the current system theme when
/// `hint` is `None`. Use this on `RunEvent::Ready`, after Tauri's dev-mode
/// icon setup has run.
pub fn refresh(hint: Option<Theme>) {
    #[cfg(target_os = "macos")]
    macos::apply(hint, true);
    #[cfg(not(target_os = "macos"))]
    let _ = hint;
}

/// Updates the Dock icon if the resolved theme differs from the last applied
/// icon.
pub fn sync(hint: Option<Theme>) {
    #[cfg(target_os = "macos")]
    macos::apply(hint, false);
    #[cfg(not(target_os = "macos"))]
    let _ = hint;
}

/// Starts the background watcher that follows the macOS icon appearance.
pub fn spawn_watcher(app: tauri::AppHandle) {
    #[cfg(target_os = "macos")]
    macos::spawn_watcher(app);
    #[cfg(not(target_os = "macos"))]
    let _ = app;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icon_style_is_independent_of_window_appearance_unless_automatic() {
        for system in [Theme::Dark, Theme::Light] {
            for default in [None, Some("RegularLight"), Some("Default")] {
                assert_eq!(resolve_theme(system, default), Some(Theme::Light));
            }
            assert_eq!(
                resolve_theme(system, Some("RegularDark")),
                Some(Theme::Dark)
            );
            assert_eq!(
                resolve_theme(system, Some("RegularAutomatic")),
                Some(system)
            );
            for style in [
                "ClearLight",
                "ClearDark",
                "ClearAutomatic",
                "TintedLight",
                "TintedDark",
                "TintedAutomatic",
            ] {
                assert_eq!(resolve_theme(system, Some(style)), None);
            }
        }
    }

    #[cfg(target_os = "macos")]
    #[test]
    fn dock_icons_decode_and_differ() {
        assert_ne!(macos::LIGHT_BYTES, macos::DARK_BYTES);
        assert!(macos::decode_icon(macos::LIGHT_BYTES).is_some());
        assert!(macos::decode_icon(macos::DARK_BYTES).is_some());
    }
}
